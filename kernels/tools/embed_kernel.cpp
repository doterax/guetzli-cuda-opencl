// embed_kernel: LZO-compresses a kernel file (OpenCL source or PTX) into a C++ header.
//
//   embed_kernel <input> <output.h> <Name>
//
// writes guetzli::kernels::k<Name>Size (the uncompressed size) and k<Name>Lzo (the LZO1X-1 stream).
// The kernels are compressed so the executable does not carry plain C-like kernel code (antivirus
// false positives). Host tool for the kernel-headers / check-kernel-headers targets
// (cmake/KernelHeaders.cmake); the output is committed, so it must be deterministic.

#include <cstdio>
#include <exception>
#include <fstream>
#include <iterator>
#include <string>
#include <vector>

#include "minilzo.h"

namespace {

bool readFile(const char* path, std::vector<unsigned char>& data) {
  std::ifstream in(path, std::ios::binary);
  if (!in) {
    return false;
  }
  data.assign(std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>());
  return !in.bad();
}

std::string formatHeader(const std::string& source_name, const std::string& name, std::size_t size,
                         const std::vector<unsigned char>& lzo) {
  std::string out;
  out += "// Generated by kernels/tools/embed_kernel.cpp from " + source_name + "; do not edit.\n";
  out += "// Regenerate with the kernel-headers CMake target and commit the result.\n";
  out += "#pragma once\n\n#include <cstddef>\n\nnamespace guetzli::kernels {\n\n";
  out += "inline constexpr std::size_t k" + name + "Size = " + std::to_string(size) + ";\n";
  out += "inline constexpr unsigned char k" + name + "Lzo[] = {";
  constexpr std::size_t kPerLine = 24;
  char hex[8];
  for (std::size_t i = 0; i < lzo.size(); ++i) {
    out += i % kPerLine == 0 ? "\n    " : " ";
    std::snprintf(hex, sizeof(hex), "0x%02x,", lzo[i]);
    out += hex;
  }
  out += "\n};\n\n}  // namespace guetzli::kernels\n";
  return out;
}

}  // namespace

int run(int argc, char** argv) {
  if (argc != 4) {
    std::fprintf(stderr, "usage: embed_kernel <input> <output.h> <Name>\n");
    return 1;
  }
  std::vector<unsigned char> input;
  if (!readFile(argv[1], input) || input.empty()) {
    std::fprintf(stderr, "embed_kernel: cannot read %s (or it is empty)\n", argv[1]);
    return 1;
  }
  if (lzo_init() != LZO_E_OK) {
    std::fprintf(stderr, "embed_kernel: lzo_init failed\n");
    return 1;
  }

  // Worst case for LZO1X-1: input + input/16 + 64 + 3.
  std::vector<unsigned char> lzo(input.size() + (input.size() / 16) + 64 + 3);
  std::vector<unsigned char> work(LZO1X_1_MEM_COMPRESS);
  lzo_uint lzo_size = lzo.size();
  if (lzo1x_1_compress(input.data(), input.size(), lzo.data(), &lzo_size, work.data()) != LZO_E_OK) {
    std::fprintf(stderr, "embed_kernel: compression failed\n");
    return 1;
  }
  lzo.resize(lzo_size);

  std::string source_name = argv[1];
  if (const auto slash = source_name.find_last_of("/\\"); slash != std::string::npos) {
    source_name.erase(0, slash + 1);
  }
  const std::string header = formatHeader(source_name, argv[3], input.size(), lzo);
  std::ofstream out(argv[2], std::ios::binary);  // binary: LF line endings on every OS
  out << header;
  if (!out.flush()) {
    std::fprintf(stderr, "embed_kernel: cannot write %s\n", argv[2]);
    return 1;
  }
  return 0;
}

int main(int argc, char** argv) {
  try {
    return run(argc, argv);
  } catch (const std::exception& e) {
    std::fprintf(stderr, "embed_kernel: %s\n", e.what());
    return 1;
  }
}
